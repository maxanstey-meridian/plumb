#!/usr/bin/env node
// MER-FE-015 — a port that mirrors a generated Rivet client one-for-one is a
// fake API abstraction: every port method name also exists as an exported
// function of a single generated client module. "Ports describe capabilities
// the page needs, not the API surface." Ships at info per FABLE_CHECKS.md
// (heuristic; T3 AST signature comparison would be needed for warn+).
// Requires >= 2 methods so a one-method port can't match by accident.
// AST-tier (v3b): TypeScript compiler API for the port side; generated client
// exports come from a regex — Rivet output is machine-regular by definition.
// DOC: frontend-pa-vsa.md#rivet-rules
import fs from "node:fs";
import path from "node:path";
import { findFeRoots, walkFiles } from "./_lib/fe-graph.mjs";
import { walkFiles as walkVisibleFiles } from "./_lib/fs-scan.mjs";

let ts;
try { ({ default: ts } = await import("typescript")); }
catch {
  process.stderr.write("MER-FE-015: typescript not installed under plumb — skipping (pnpm install in ~/Sites/plumb)\n");
  process.exit(0);
}

const root = process.argv[2];

// generated client modules: <name>.ts files under a */generated/* dir carrying
// the Rivet header. Map of file -> Set<exported function name>.
const clientExports = new Map();
(function walk(d) {
  for (const p of walkVisibleFiles(d, d, { filter: (name) => name.endsWith(".ts") })) {
    if (!/\/generated\//.test(p)) continue;
    const src = fs.readFileSync(p, "utf8");
    if (!/Generated by Rivet/i.test(src)) continue;
    const names = new Set([...src.matchAll(/^export (?:async )?function (\w+)/gm)].map((m) => m[1]));
    if (names.size) clientExports.set(p, names);
  }
})(root);
if (!clientExports.size) process.exit(0);

for (const feRoot of findFeRoots(root)) {
  const appDir = fs.existsSync(path.join(feRoot, "app")) ? path.join(feRoot, "app") : feRoot;
  for (const f of walkFiles(appDir, /\.ts$/)) {
    if (!/\/ports\//.test(f) || f.endsWith(".d.ts") || /\.(spec|test)\.ts$/.test(f) || /__tests__/.test(f)) continue;
    const sf = ts.createSourceFile(f, fs.readFileSync(f, "utf8"), ts.ScriptTarget.Latest, true);
    for (const st of sf.statements) {
      if (!ts.isInterfaceDeclaration(st)) continue;
      const methods = st.members
        .filter((m) => ts.isMethodSignature(m) ||
          (ts.isPropertySignature(m) && m.type && ts.isFunctionTypeNode(m.type)))
        .map((m) => m.name?.getText(sf))
        .filter(Boolean);
      if (methods.length < 2) continue;
      for (const [client, names] of clientExports) {
        if (!methods.every((m) => names.has(m))) continue;
        const line = sf.getLineAndCharacterOfPosition(st.getStart(sf)).line + 1;
        console.log(
          `MER-FE-015\tinfo\t${path.relative(root, f)}:${line}\tport ${st.name.text} mirrors generated client ${path.relative(root, client)} one-for-one (${methods.join(", ")}) — a fake API abstraction; shape the port around what the page needs\tfrontend-pa-vsa.md#rivet-rules`
        );
        break;
      }
    }
  }
}
